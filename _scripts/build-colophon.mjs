// Generates COLOPHON.md — the entry point of the design system.
//
// Why generated and not written by hand: a hand-maintained entry point drifts
// from what actually sits in the directory, and then it costs the reader more
// time than it saves. This one cannot lie, because it reads instead of
// asserting. It is thereby also the characterization that cupertino-longevity
// flagged as missing (characterization 2 of 5).
//
// Call:  node _scripts/build-colophon.mjs [target directory]

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = process.argv[2] || process.cwd();

function walk(dir, base = dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith(".") || e.name === "node_modules") continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, base, out);
    else out.push({ path: relative(base, p), size: statSync(p).size });
  }
  return out;
}

// Pull measurements from the artefacts, do not type them in.
function readMeasurements() {
  const m = { tokens: null, texture: null };
  const tj = join(ROOT, "tokens", "tokens.json");
  if (existsSync(tj)) {
    try {
      const d = JSON.parse(readFileSync(tj, "utf8"));
      m.tokens = { bands: Object.keys(d.bands || {}), contrast: d.contrast || null,
                   generatedBy: d.generatedBy || null, allTargetsMet: d.allTargetsMet };
    } catch { /* unreadable is itself a finding */ }
  }
  const lab = join(ROOT, "tokens", "texture-lab.html");
  if (existsSync(lab)) {
    const src = readFileSync(lab, "utf8");
    const variants = [...src.matchAll(/key:\s*'([a-z]+)'/g)].map(x => x[1]);
    m.texture = { variants, lab: "tokens/texture-lab.html" };
  }
  return m;
}

const files = walk(ROOT).filter(f => !f.path.startsWith("COLOPHON"));
const byDir = {};
for (const f of files) {
  const d = f.path.includes("/") ? f.path.split("/")[0] : "(root)";
  (byDir[d] ||= []).push(f);
}
const m = readMeasurements();

const L = [];
L.push("# Colophon");
L.push("");
L.push("What this system is made of. Generated by `_scripts/build-colophon.mjs` —");
L.push("do not edit by hand, or it will drift from what is actually here.");
L.push("");
L.push(`As of: ${new Date().toISOString().slice(0, 10)} · ${files.length} files`);
L.push("");
L.push("## Start here");
L.push("");
if (existsSync(join(ROOT, "tokens", "colors.css"))) {
  L.push("- `tokens/colors.css` — the colour roles. One set of names, two sets of values.");
}
if (m.texture) {
  L.push(`- \`${m.texture.lab}\` — the material, with its own measurement alongside.`);
}
// The build directory is `_scripts`, not `scripts`. This check named the old path and
// therefore silently dropped the single most important line in the file — the same
// made-up-path defect the note below already records for content/projects.json, which
// is exactly why a generated colophon has to be checked against the directory too.
if (existsSync(join(ROOT, "_scripts", "derive-tokens.mjs"))) {
  L.push("- `_scripts/derive-tokens.mjs` — how the values come to be. The script is the specification.");
}
L.push("");
L.push("## Measured");
L.push("");
if (m.tokens?.contrast) {
  L.push("| Band | Role | Hex | vs paper | vs alt | vs dim |");
  L.push("|---|---|---|---|---|---|");
  for (const [band, roles] of Object.entries(m.tokens.contrast)) {
    for (const [role, v] of Object.entries(roles)) {
      L.push(`| ${band} | \`--${role}\` | \`${v.hex ?? "?"}\` | ${v.vsPaper ?? "?"} | ${v.vsAlt ?? "?"} | ${v.vsDim ?? "?"} |`);
    }
  }
  if (m.tokens.allTargetsMet === false) {
    L.push("");
    L.push("⚠️ At least one text role misses its target — `npm run tokens` reports which.");
  }
} else {
  L.push("_No token measurement present._ Once `tokens/tokens.json` exists, it will show here.");
}
L.push("");
if (m.texture) {
  L.push(`Texture variants in the lab: ${m.texture.variants.map(v => `\`${v}\``).join(", ")}.`);
  L.push("Each is checked against the flat ground for luminance neutrality and isotropy.");
  L.push("");
}
L.push("## What lies here");
L.push("");
for (const [dir, fs_] of Object.entries(byDir).sort()) {
  const kb = (fs_.reduce((a, b) => a + b.size, 0) / 1024).toFixed(1);
  L.push(`**${dir}** — ${fs_.length} file(s), ${kb} kB`);
  for (const f of fs_.sort((a, b) => a.path.localeCompare(b.path))) {
    L.push(`- \`${f.path}\``);
  }
  L.push("");
}
L.push("## What is still missing");
L.push("");
const missing = [
  ["Mark", existsSync(join(ROOT, "assets", "mark.svg"))],
  ["Imagery layer", existsSync(join(ROOT, "imagery"))],
  // This path used to be called data/content.json and never existed. A colophon
  // that checks against a made-up path permanently reports "missing" and thereby
  // becomes useless — it then reports not the inventory but its own typos.
  ["Content model: projects", existsSync(join(ROOT, "content", "projects.json"))],
  ["Content model: publications", existsSync(join(ROOT, "content", "publications.json"))],
];
for (const [name, present] of missing) {
  L.push(`- ${present ? "present" : "**missing**"} — ${name}`);
}
L.push("");
L.push("A colophon also names what is not there. Otherwise it would be advertising.");
L.push("");

writeFileSync(join(ROOT, "COLOPHON.md"), L.join("\n"));
console.log(`COLOPHON.md written — ${files.length} files captured, ${L.length} lines.`);
